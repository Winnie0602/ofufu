const createMockExample = (
  id: string,
  japanese: string,
  highlightedText: string,
  translation: string,
): VocabularyExample => {
  const highlightStart = japanese.indexOf(highlightedText)

  if (highlightStart === -1) {
    return {
      id,
      japanese,
      segments: [{ text: japanese, highlighted: false }],
      translation,
    }
  }

  const highlightEnd = highlightStart + highlightedText.length

  return {
    id,
    japanese,
    segments: [
      { text: japanese.slice(0, highlightStart), highlighted: false },
      { text: japanese.slice(highlightStart, highlightEnd), highlighted: true },
      { text: japanese.slice(highlightEnd), highlighted: false },
    ].filter((segment) => segment.text.length > 0),
    translation,
  }
}

